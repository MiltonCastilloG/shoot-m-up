// Generates the game's 3D assets as Wavefront OBJ + MTL files.
//
// OBJ is a plain-text format, so every file this writes can be opened
// directly in Blender, tweaked, and re-exported over the same name.
// Re-run with `node assets/models/generate.js` to rebuild from scratch.
//
// Coordinate convention (shared with the web client):
//   - 1 unit = one grid cell
//   - the 5x5 field is centred on the origin, cells at x/z in {-2,-1,0,1,2}
//   - +y is up; a tile's top surface sits at y = 0

const fs = require('fs');
const path = require('path');

const OUT = __dirname;

function fmt(n) {
  return (Math.round(n * 1e6) / 1e6).toString();
}

// Axis-aligned box centred at (cx,cy,cz). Faces wound counter-clockwise
// when viewed from outside, each with a single flat normal.
function box(cx, cy, cz, w, h, d) {
  const hx = w / 2;
  const hy = h / 2;
  const hz = d / 2;
  const v = [
    [cx - hx, cy - hy, cz - hz],
    [cx + hx, cy - hy, cz - hz],
    [cx + hx, cy - hy, cz + hz],
    [cx - hx, cy - hy, cz + hz],
    [cx - hx, cy + hy, cz - hz],
    [cx + hx, cy + hy, cz - hz],
    [cx + hx, cy + hy, cz + hz],
    [cx - hx, cy + hy, cz + hz],
  ];
  const f = [
    [[0, 1, 2, 3], [0, -1, 0]], // bottom
    [[7, 6, 5, 4], [0, 1, 0]], // top
    [[3, 2, 6, 7], [0, 0, 1]], // front (+z)
    [[1, 0, 4, 5], [0, 0, -1]], // back (-z)
    [[2, 1, 5, 6], [1, 0, 0]], // right (+x)
    [[0, 3, 7, 4], [-1, 0, 0]], // left (-x)
  ];
  return { v, f };
}

// Faceted octahedral "gem" centred at (cx,cy,cz) with per-axis radii.
function octa(cx, cy, cz, rx, ry, rz) {
  const v = [
    [cx, cy + ry, cz], // 0 top
    [cx + rx, cy, cz], // 1 +x
    [cx, cy, cz + rz], // 2 +z
    [cx - rx, cy, cz], // 3 -x
    [cx, cy, cz - rz], // 4 -z
    [cx, cy - ry, cz], // 5 bottom
  ];
  const s = 0.57735; // 1/sqrt(3)
  const f = [
    [[0, 2, 1], [s, s, s]],
    [[0, 3, 2], [-s, s, s]],
    [[0, 4, 3], [-s, s, -s]],
    [[0, 1, 4], [s, s, -s]],
    [[5, 1, 2], [s, -s, s]],
    [[5, 2, 3], [-s, -s, s]],
    [[5, 3, 4], [-s, -s, -s]],
    [[5, 4, 1], [s, -s, -s]],
  ];
  return { v, f };
}

function writeModel(name, groups, matName) {
  const vLines = [];
  const nLines = [];
  const body = [];
  let vCount = 0;
  let nCount = 0;

  for (const [groupName, shape] of groups) {
    const offset = vCount;
    for (const vert of shape.v) {
      vLines.push(`v ${vert.map(fmt).join(' ')}`);
      vCount++;
    }
    body.push(`o ${groupName}`);
    body.push(`usemtl ${matName}`);
    body.push('s off');
    for (const [idx, normal] of shape.f) {
      nLines.push(`vn ${normal.map(fmt).join(' ')}`);
      nCount++;
      const face = idx.map((i) => `${offset + i + 1}//${nCount}`).join(' ');
      body.push(`f ${face}`);
    }
  }

  const out = [
    `# ${name}.obj - Untitled Music Game`,
    `# Generated by assets/models/generate.js - safe to open and edit in Blender.`,
    `mtllib ${name}.mtl`,
    '',
    ...vLines,
    '',
    ...nLines,
    '',
    ...body,
    '',
  ].join('\n');

  fs.writeFileSync(path.join(OUT, `${name}.obj`), out);
}

function writeMtl(name, matName, { kd, ke, ns = 80 }) {
  const out = [
    `# ${name}.mtl - Untitled Music Game`,
    `# Kd = base colour, Ke = emission (the neon glow the web client blooms).`,
    `newmtl ${matName}`,
    'Ka 0 0 0',
    `Kd ${kd.map(fmt).join(' ')}`,
    'Ks 0.25 0.25 0.25',
    `Ke ${ke.map(fmt).join(' ')}`,
    `Ns ${ns}`,
    'd 1',
    'illum 2',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(OUT, `${name}.mtl`), out);
}

// --- the assets -----------------------------------------------------------

// One grid cell. Thin panel, top face flush with y = 0.
writeModel('tile', [['Tile', box(0, -0.06, 0, 1.0, 0.12, 1.0)]], 'tile_neon');
writeMtl('tile', 'tile_neon', { kd: [0.04, 0.05, 0.08], ke: [0.0, 0.16, 0.2] });

// The player marker you slide left/right to dodge. Pad + raised core.
writeModel(
  'player',
  [
    ['Pad', box(0, 0.08, 0, 0.9, 0.16, 0.9)],
    ['Core', box(0, 0.3, 0, 0.5, 0.4, 0.5)],
  ],
  'player_neon',
);
writeMtl('player', 'player_neon', { kd: [0.9, 0.12, 0.55], ke: [0.75, 0.06, 0.42] });

// A falling hazard note.
writeModel('note', [['Note', octa(0, 0, 0, 0.32, 0.46, 0.32)]], 'note_neon');
writeMtl('note', 'note_neon', { kd: [0.15, 0.9, 0.95], ke: [0.12, 0.82, 0.92] });

// A single health pip.
writeModel('pip', [['Pip', octa(0, 0, 0, 0.16, 0.22, 0.16)]], 'pip_neon');
writeMtl('pip', 'pip_neon', { kd: [0.3, 1.0, 0.55], ke: [0.16, 0.78, 0.36] });

// The border around the play field: four bars.
const T = 0.22; // bar thickness
const FH = 0.34; // bar height
const SPAN = 5.2; // inner span of the field
const ARM = 2.61; // centre offset of each bar
writeModel(
  'frame',
  [
    ['Frame_North', box(0, FH / 2, -ARM, SPAN + T, FH, T)],
    ['Frame_South', box(0, FH / 2, ARM, SPAN + T, FH, T)],
    ['Frame_West', box(-ARM, FH / 2, 0, T, FH, SPAN + T)],
    ['Frame_East', box(ARM, FH / 2, 0, T, FH, SPAN + T)],
  ],
  'frame_neon',
);
writeMtl('frame', 'frame_neon', { kd: [0.45, 0.18, 0.85], ke: [0.34, 0.12, 0.74] });

console.log('wrote tile, player, note, pip, frame (.obj + .mtl) to', OUT);
